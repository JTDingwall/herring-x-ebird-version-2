 "Resource pulses are episodic, high-magnitude inputs of food that punctuate "
 "much longer intervals of scarcity, and they are a recurrent feature of "
 "coastal ecosystems (Yang et al. 2008; Holt 2008). Consumer responses to such "
 "inputs are typically behavioural before they are demographic; animals "
